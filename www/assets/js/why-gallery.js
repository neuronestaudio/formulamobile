/* Why-ceramic poster: eight reason pills, a scroll-snap carousel per reason (slides mixed across
   the four albums), the outlined keyword behind the slide row, and a <dialog> lightbox.
   Markup is generated by tools/why/build_why.py. Without JS every slide is still a plain
   link to its full-size image, and the track still scrolls. */
(function () {
  var root = document.querySelector('[data-wg]');
  if (!root) return;
  var tabs = [].slice.call(root.querySelectorAll('.wg-tab'));
  var panels = [].slice.call(root.querySelectorAll('.wg-panel'));
  var count = root.querySelector('.wg-count');
  var bar = root.querySelector('.wg-progress span');
  var arrows = [].slice.call(root.querySelectorAll('.wg-nav .wg-arrow'));
  var reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  var active = 0;
  var ghost = root.querySelector('.wg-ghost');

  function pad(n) { return (n < 10 ? '0' : '') + n; }
  function track(i) { return panels[i === undefined ? active : i].querySelector('.wg-track'); }
  function slides(i) { return [].slice.call(track(i).children); }
  function step(t) { var s = t.children; return s.length > 1 ? s[1].offsetLeft - s[0].offsetLeft : t.clientWidth; }

  function sync() {
    var t = track(), max = t.scrollWidth - t.clientWidth, n = t.children.length;
    var idx = Math.min(n - 1, Math.round(t.scrollLeft / step(t)));
    if (max > 0 && t.scrollLeft >= max - 2) idx = n - 1;
    count.innerHTML = '<b>' + pad(idx + 1) + '</b> / ' + pad(n);
    var w = max > 0 ? t.clientWidth / t.scrollWidth : 1, p = max > 0 ? t.scrollLeft / max : 0;
    bar.style.width = (w * 100) + '%';
    bar.style.left = (p * (1 - w) * 100) + '%';
    t.classList.toggle('at-end', max <= 0 || t.scrollLeft >= max - 2);
    arrows[0].disabled = t.scrollLeft <= 2;
    arrows[1].disabled = max <= 0 || t.scrollLeft >= max - 2;
  }

  function show(i, focus) {
    active = i;
    tabs.forEach(function (b, k) {
      b.classList.toggle('is-on', k === i);
      b.setAttribute('aria-selected', k === i ? 'true' : 'false');
      b.tabIndex = k === i ? 0 : -1;
    });
    panels.forEach(function (p, k) { p.hidden = k !== i; });
    if (ghost) { ghost.textContent = tabs[i].getAttribute('data-ghost') || ''; ghost.classList.remove('is-in'); void ghost.offsetWidth; ghost.classList.add('is-in'); }
    var strip = tabs[i].parentNode;                 /* phones: the pills are one scrolling row */
    if (strip.scrollWidth > strip.clientWidth) strip.scrollTo({ left: tabs[i].offsetLeft - (strip.clientWidth - tabs[i].offsetWidth) / 2, behavior: reduce ? 'auto' : 'smooth' });
    track().scrollLeft = 0;
    if (focus) tabs[i].focus();
    sync();
  }

  tabs.forEach(function (b, i) {
    b.addEventListener('click', function () { show(i); });
    b.addEventListener('keydown', function (e) {
      var d = e.key === 'ArrowRight' ? 1 : e.key === 'ArrowLeft' ? -1 : 0;
      if (!d) return;
      e.preventDefault();
      show((i + d + tabs.length) % tabs.length, true);
    });
  });

  arrows.forEach(function (a) {
    a.addEventListener('click', function () {
      var t = track();
      t.scrollBy({ left: step(t) * (+a.getAttribute('data-dir')), behavior: reduce ? 'auto' : 'smooth' });
    });
  });

  /* mouse drag-to-scroll; a drag must not count as a click on the slide */
  panels.forEach(function (p) {
    var t = p.querySelector('.wg-track'), down = false, moved = false, x0 = 0, s0 = 0, raf = 0;
    t.addEventListener('scroll', function () { if (!raf) raf = requestAnimationFrame(function () { raf = 0; sync(); }); }, { passive: true });
    t.addEventListener('pointerdown', function (e) {
      if (e.pointerType !== 'mouse' || e.button !== 0) return;
      down = true; moved = false; x0 = e.clientX; s0 = t.scrollLeft;
    });
    window.addEventListener('pointermove', function (e) {
      if (!down) return;
      var dx = e.clientX - x0;
      if (!moved && Math.abs(dx) > 6) { moved = true; t.classList.add('is-drag'); }
      if (moved) t.scrollLeft = s0 - dx;
    });
    window.addEventListener('pointerup', function () {
      if (!down) return;
      down = false;
      if (moved) {
        t.classList.remove('is-drag');
        var st = step(t);
        t.scrollTo({ left: Math.round(t.scrollLeft / st) * st, behavior: reduce ? 'auto' : 'smooth' });
      }
    });
    t.addEventListener('click', function (e) {
      if (moved) { e.preventDefault(); e.stopPropagation(); moved = false; return; }
      var a = e.target.closest('a');
      if (!a || !lb || !lb.showModal) return;
      e.preventDefault();
      open(slides().indexOf(a.parentNode));
    }, true);
    t.addEventListener('dragstart', function (e) { e.preventDefault(); });
  });

  /* lightbox */
  var lb = document.querySelector('.wg-lb'), cur = 0;
  var lbImg = lb && lb.querySelector('img'), lbMeta = lb && lb.querySelector('.wg-lb-meta'), lbText = lb && lb.querySelector('.wg-lb-text');

  function paint() {
    var list = slides(), a = list[cur].querySelector('a'), im = a.querySelector('img');
    lbImg.src = a.getAttribute('href');
    lbImg.alt = im.alt;
    lbMeta.textContent = tabs[active].getAttribute('data-name') + ' · ' + pad(cur + 1) + ' / ' + pad(list.length);
    lbText.textContent = a.getAttribute('data-cap') || im.alt;
    [cur - 1, cur + 1].forEach(function (k) {           /* warm the neighbours */
      if (list[k]) { var pre = new Image(); pre.src = list[k].querySelector('a').getAttribute('href'); }
    });
  }
  function open(i) { cur = i; paint(); document.documentElement.classList.add('wg-lock'); lb.showModal(); lb.focus(); }
  function go(d) { var n = slides().length; cur = (cur + d + n) % n; paint(); }

  if (lb) {
    lb.addEventListener('close', function () {
      document.documentElement.classList.remove('wg-lock');
      var s = slides()[cur]; if (s) { s.scrollIntoView({ block: 'nearest', inline: 'center' }); s.querySelector('a').focus({ preventScroll: true }); }
    });
    lb.addEventListener('click', function (e) {
      if (e.target === lb || e.target.closest('.wg-lb-x')) return lb.close();
      var a = e.target.closest('.wg-lb-a'); if (a) go(+a.getAttribute('data-dir'));
    });
    lb.addEventListener('keydown', function (e) {
      if (e.key === 'ArrowRight') go(1); else if (e.key === 'ArrowLeft') go(-1);
    });
    var tx = null;
    lb.addEventListener('touchstart', function (e) { tx = e.touches[0].clientX; }, { passive: true });
    lb.addEventListener('touchend', function (e) {
      if (tx === null) return;
      var dx = e.changedTouches[0].clientX - tx; tx = null;
      if (Math.abs(dx) > 48) go(dx < 0 ? 1 : -1);
    });
  }

  window.addEventListener('resize', sync);
  /* the track can be measured before it has a width (hidden ancestor, late fonts): re-sync when it changes */
  if (window.ResizeObserver) new ResizeObserver(sync).observe(root);
  show(0);
})();
